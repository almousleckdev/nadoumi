package com.nadoumi.payment.pdf;

import java.util.ArrayList;
import java.util.List;
import org.springframework.stereotype.Component;

/** The payment receipt: one page, same masthead, watermark and footer as the application form. */
@Component
public class ReceiptPdf {

    public static final String TITLE = "Payment Receipt";

    private final PdfRenderer renderer;

    public ReceiptPdf(PdfRenderer renderer) {
        this.renderer = renderer;
    }

    public byte[] render(ReceiptModel m) {
        return renderer.render(TITLE + " " + m.receiptNo(), m.receiptNo(), m.verifyUrl(), page -> {
            page.masthead(TITLE, List.of(
                    new String[] {"Receipt no.", m.receiptNo()},
                    new String[] {"Issued", PdfText.stamp(m.issuedAt())},
                    new String[] {"Application", m.applicationRef()}));

            page.section(1, "Paid by");
            page.pairs(List.of(
                    new String[] {"Name", m.studentName()},
                    new String[] {"Applicant ID", m.studentPublicId()},
                    new String[] {"Email", m.studentEmail()}));

            page.section(2, "For");
            List<String[]> purpose = new ArrayList<>();
            purpose.add(new String[] {"Service", "Nadoumi application fee"});
            purpose.add(new String[] {"Application", m.applicationRef()});
            purpose.add(new String[] {"Applying for", m.opportunityTitle()});
            if (m.universityName() != null) {
                purpose.add(new String[] {"University", m.universityName()});
            }
            if (m.intake() != null) {
                purpose.add(new String[] {"Intake", PdfText.label(m.intake())});
            }
            page.pairs(purpose);

            page.section(3, "Payment");
            page.pairs(List.of(
                    new String[] {"Method", "QR payment"},
                    new String[] {"Paid to", m.payee()},
                    new String[] {"Payment reference", m.paymentReference()},
                    new String[] {"Transaction no.", m.transactionNo()},
                    new String[] {"Confirmed", PdfText.stamp(m.paidAt())},
                    new String[] {"Confirmed by", "Nadoumi finance team"}));

            page.amountPanel("Amount paid", PdfText.money(m.amount(), m.currency()), "PAID");

            page.note("The application fee is non-refundable. This receipt is generated by the Nadoumi system "
                    + "and is valid without a signature. Keep it as your proof of payment.");
        });
    }
}
